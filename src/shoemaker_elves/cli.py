class Orchestrator:
    def __init__(self, args):
        self.args = args
        self.project_dir = Path(args.project_dir).resolve()
        orchestrator_dir = get_orchestrator_dir()
        self.state_path = str(orchestrator_dir / "state.json")
        self.state = State(self.state_path)
        self.context_md = ContextMDManager(self.project_dir)
        self.docs_manager = DocsManager(self.project_dir)
        self.gpt = None
        self.shutting_down = False

        # Initialize logger with log directory in .claude/logs
        log_dir = self.project_dir / ".claude" / "logs"
        self.logger = Logger(
            log_dir=log_dir, enable_rich=not args.verbose if hasattr(args, "verbose") else True
        )

        # Load and merge config
        self.config = load_config()
        self.config = merge_env_overrides(self.config)

        # Apply CLI flag overrides (flags have highest priority)
        self._apply_flag_overrides()

        # Set up signal handler for graceful shutdown
        signal.signal(signal.SIGINT, self._handle_shutdown)
        signal.signal(signal.SIGTERM, self._handle_shutdown)

    def _apply_flag_overrides(self):
        """Apply CLI flag overrides to config (flags have highest priority)."""
        # Agent model
        if hasattr(self.args, "agent_model") and self.args.agent_model:
            self.config["agent"]["model"] = self.args.agent_model

        # Max cost
        if hasattr(self.args, "max_cost_usd") and self.args.max_cost_usd is not None:
            self.config["planner"]["max_cost_usd"] = self.args.max_cost_usd

        # GPT model (deprecated, but still supported)
        if hasattr(self.args, "gpt_model") and self.args.gpt_model:
            self.config["planner"]["model"] = self.args.gpt_model

        # Planner provider
        if hasattr(self.args, "planner_provider") and self.args.planner_provider:
            self.config["planner"]["provider"] = self.args.planner_provider
        # Legacy provider flag
        elif hasattr(self.args, "provider") and self.args.provider:
            self.config["planner"]["provider"] = self.args.provider

        # Planner model
        if hasattr(self.args, "planner_model") and self.args.planner_model:
            self.config["planner"]["model"] = self.args.planner_model

        # Planner base URL
        if hasattr(self.args, "planner_base_url") and self.args.planner_base_url:
            self.config["planner"]["base_url"] = self.args.planner_base_url
        # Legacy base_url flag
        elif hasattr(self.args, "base_url") and self.args.base_url:
            self.config["planner"]["base_url"] = self.args.base_url

        # API key (legacy flag)
        if hasattr(self.args, "openai_api_key") and self.args.openai_api_key:
            self.config["planner"]["api_key"] = self.args.openai_api_key

        # Azure-specific flags
        if hasattr(self.args, "azure_endpoint") and self.args.azure_endpoint:
            if "azure" not in self.config:
                self.config["azure"] = {}
            self.config["azure"]["endpoint"] = self.args.azure_endpoint

        if hasattr(self.args, "azure_deployment") and self.args.azure_deployment:
            if "azure" not in self.config:
                self.config["azure"] = {}
            self.config["azure"]["deployment"] = self.args.azure_deployment

        if hasattr(self.args, "azure_api_version") and self.args.azure_api_version:
            if "azure" not in self.config:
                self.config["azure"] = {}
            self.config["azure"]["api_version"] = self.args.azure_api_version

    def _handle_shutdown(self, signum, frame):
        """Graceful shutdown: set flag, let the polling loop handle cleanup.

        Avoids file I/O in signal handler to prevent deadlocks if signal
        arrives while a file lock is held.
        """
        if self.shutting_down:
            # Second interrupt — force exit
            print("\nForce quitting...")
            sys.exit(1)

        self.shutting_down = True
        print("\n\nShutting down gracefully...")
        print("  (Current task will finish but no new tasks will start)")

    def validate(self):
        """Validate prerequisites."""
        if not self.project_dir.is_dir():
            self.logger.error(f"Project directory not found: {self.project_dir}")
            sys.exit(1)

        # Check agent CLI
        try:
            result = subprocess.run(
                ["claude", "--version"],
                capture_output=True,
                text=True,
                timeout=10,
            )
            if result.returncode != 0:
                self.logger.error("AI agent CLI not found or not working")
                sys.exit(1)
        except (FileNotFoundError, subprocess.TimeoutExpired):
            self.logger.error("AI agent CLI not found. Install it first.")
            sys.exit(1)

        if self.args.gpt:
            if not self.args.description:
                self.logger.error("--description is required with --gpt mode")
                sys.exit(1)

            # Get API key from config
            api_key = self.config["planner"].get("api_key")
            if not api_key:
                self.logger.error("API key not found in config or environment")
                self.logger.info(
                    "Run 'shoemaker-elves init' to configure, or set environment variable"
                )
                sys.exit(1)

            lazy_import_gpt()
            provider = self.config["planner"]["provider"]
            model = self.config["planner"]["model"]

            # Initialize GPTPlanner with provider-specific settings
            if provider == "azure_openai":
                azure_config = self.config.get("azure", {})
                self.gpt = GPTPlanner(
                    api_key=api_key,
                    model=model,
                    provider=provider,
                    azure_endpoint=azure_config.get("endpoint"),
                    azure_deployment=azure_config.get("deployment"),
                    azure_api_version=azure_config.get("api_version"),
                )
            elif provider == "openai_compatible":
                self.gpt = GPTPlanner(
                    api_key=api_key,
                    model=model,
                    provider=provider,
                    base_url=self.config["planner"].get("base_url"),
                )
            else:
                self.gpt = GPTPlanner(
                    api_key=api_key,
                    model=model,
                    provider=provider,
                )

    def run(self):
        """Main orchestration loop."""
        self.validate()

        # Display header
        self.logger.header("Shoemaker Elves")

        # Display configuration
        config_lines = [
            f"Project:  {self.project_dir}",
            f"Mode:     {'GPT' if self.args.gpt else 'Manual'}",
            f"Agent:    {self.config['agent']['model']}",
        ]

        if self.args.gpt:
            config_lines.extend(
                [
                    f"Provider: {self.config['planner']['provider']}",
                    f"Model:    {self.config['planner']['model']}",
                    f"Batches:  {self.args.max_batches} x {self.args.batch_size} tasks",
                ]
            )

        config_lines.append(f"Cost cap: ${self.config['planner']['max_cost_usd']:.2f}")

        if is_rich_available():
            config_lines.append("Rich UI:  Enabled")

        for line in config_lines:
            self.logger.print(f"  {line}")

        print()  # Add spacing

        if self.args.resume:
            self._resume()
        elif self.args.gpt:
            self._run_gpt_mode()
        else:
            self._run_manual_mode()

    def _run_manual_mode(self):
        """Run tasks from tasks/ directory."""
        tasks = discover_manual_tasks()
        if not tasks:
            self.logger.error("No task files found in tasks/ directory.")
            self.logger.info("Create numbered markdown files: tasks/1.md, tasks/2.md, ...")
            sys.exit(1)

        self.logger.info(f"Found {len(tasks)} task(s):")

        # Display tasks in a table if rich is available
        if is_rich_available():
            rows = [[str(i + 1), t["title"], t["file"]] for i, t in enumerate(tasks)]
            self.logger.table("Planned Tasks", ["#", "Title", "File"], rows)
        else:
            for t in tasks:
                print(f"  • {t['file']}: {t['title']}")
            print()

        config = {
            "agent_model": self.config["agent"]["model"],
            "max_cost_usd": self.config["planner"]["max_cost_usd"],
            "task_timeout": self.args.task_timeout,
        }

        orchestrator_dir = get_orchestrator_dir()

        # Initialize state
        State.create_initial(
            path=self.state_path,
            project_dir=str(self.project_dir),
            orchestrator_dir=str(orchestrator_dir),
            tasks=tasks,
            config=config,
            mode="manual",
        )

        # Set up project
        self.context_md.backup()
        self.context_md.write_initial()
        self.docs_manager.setup()
        install_hook(self.project_dir)

        # Mark first task as running with timestamp
        self.state.mark_task_running(0)

        # Launch first task
        first_task = tasks[0]
        self.logger.info(f"Starting task 1/{len(tasks)}: {first_task['title']}")
        launch_agent_task(str(self.project_dir), first_task["file"], config)

        # Poll until done
        self._poll_until_complete()

        # Cleanup
        self._cleanup()

    def _run_gpt_mode(self):
        """Run with GPT generating batches of tasks."""
        description = self.args.description

        # Read description from file if it's a path
        if os.path.isfile(description):
            description = Path(description).read_text().strip()

        config = {
            "agent_model": self.config["agent"]["model"],
            "max_cost_usd": self.config["planner"]["max_cost_usd"],
            "task_timeout": self.args.task_timeout,
            "gpt_model": self.config["planner"]["model"],
        }

        self.context_md.backup()
        self.docs_manager.setup()
        install_hook(self.project_dir)

        cumulative_summary = ""
        previous_results = []
        total_task_index = 0

        orchestrator_dir = get_orchestrator_dir()

        for batch_num in range(1, self.args.max_batches + 1):
            if self.shutting_down:
                break

            self.logger.section(f"Batch {batch_num}/{self.args.max_batches}")

            # Ask GPT to plan tasks
            self.logger.info(f"Asking GPT to plan batch {batch_num}...")
            gpt_tasks = self.gpt.plan_batch(
                description=description,
                batch_num=batch_num,
                max_batches=self.args.max_batches,
                batch_size=self.args.batch_size,
                previous_results=previous_results,
                cumulative_summary=cumulative_summary,
            )

            if not gpt_tasks:
                self.logger.success("GPT says project is complete!")
                break

            # Write tasks to files
            task_entries = self.gpt.write_tasks_to_files(
                gpt_tasks, str(orchestrator_dir), start_index=total_task_index
            )

            self.logger.info(f"Generated {len(task_entries)} tasks:")

            # Display generated tasks in a table if rich is available
            if is_rich_available():
                rows = [[str(i + 1), t["title"]] for i, t in enumerate(task_entries)]
                self.logger.table("Generated Tasks", ["#", "Title"], rows)
            else:
                for t in task_entries:
                    print(f"    • {t['title']}")

            # Create or update state
            if batch_num == 1:
                State.create_initial(
                    path=self.state_path,
                    project_dir=str(self.project_dir),
                    orchestrator_dir=str(orchestrator_dir),
                    tasks=task_entries,
                    config=config,
                    mode="gpt",
                )
            else:
                # Add new batch tasks to existing state
                state_data = self.state.read()
                new_indices = []
                for t in task_entries:
                    idx = len(state_data["tasks"])
                    new_indices.append(idx)
                    state_data["tasks"].append(
                        {
                            "index": idx,
                            "title": t["title"],
                            "file": t["file"],
                            "status": "pending",
                            "session_id": None,
                            "transcript_path": None,
                            "result_summary": None,
                            "files_modified": [],
                            "cost_usd": 0,
                        }
                    )
                state_data["current_batch"] = batch_num
                state_data["current_task_index"] = new_indices[0]
                state_data["batches"][str(batch_num)] = {
                    "task_indices": new_indices,
                    "status": "running",
                }
                self.state.write(state_data)

            # Update CLAUDE.md
            self.context_md.rewrite_with_summary(description, cumulative_summary)

            # Mark first task of batch as running
            state_data = self.state.read()
            first_idx = state_data["current_task_index"]
            # Mark first task as running with timestamp
            self.state.mark_task_running(first_idx)

            # Launch first task
            first_task = task_entries[0]
            self.logger.info(f"Starting: {first_task['title']}")
            launch_agent_task(str(self.project_dir), first_task["file"], config)

            # Poll until batch complete
            self._poll_until_batch_complete(batch_num)

            if self.shutting_down:
                break

            # Gather batch results for GPT assessment
            state_data = self.state.read()
            batch_info = state_data["batches"][str(batch_num)]
            batch_results = []
            for idx in batch_info["task_indices"]:
                task = state_data["tasks"][idx]
                batch_results.append(
                    {
                        "title": task["title"],
                        "success": task["status"] == "completed",
                        "result_summary": task.get("result_summary", ""),
                        "files_modified": task.get("files_modified", []),
                        "errors": [],
                    }
                )

            # GPT assessment
            self.logger.info(f"Asking GPT to assess batch {batch_num}...")
            assessment = self.gpt.assess_batch(
                description=description,
                batch_num=batch_num,
                batch_results=batch_results,
                previous_summary=cumulative_summary,
            )

            cumulative_summary = assessment.get("cumulative_summary", cumulative_summary)
            previous_results = batch_results
            total_task_index += len(task_entries)

            complete_pct = assessment.get("completion_percentage", 0)
            self.logger.info(f"Assessment: {complete_pct}% complete")
            if assessment.get("issues"):
                for issue in assessment["issues"]:
                    self.logger.warning(issue)

            if assessment.get("project_complete"):
                self.logger.success("GPT says project is complete!")
                break

            # Check cost
            if state_data.get("total_cost_usd", 0) >= self.config["planner"]["max_cost_usd"]:
                self.logger.warning(f"Cost ceiling reached: ${state_data['total_cost_usd']:.2f}")
                break

        self._cleanup()

    def _resume(self):
        """Resume from existing state file with stall detection."""
        if not self.state.exists():
            print("No state file found. Nothing to resume.")
            sys.exit(1)

        state_data = self.state.read()
        print(f"Resuming from state: {state_data.get('status')}")
        print(f"  Tasks: {len(state_data.get('tasks', []))}")
        print(f"  Cost so far: ${state_data.get('total_cost_usd', 0):.2f}")

        # Detect stalled tasks
        tasks = state_data.get("tasks", [])
        stalled_tasks = []
        task_timeout = self.args.task_timeout if hasattr(self.args, "task_timeout") else 600

        now = datetime.now(timezone.utc)
        for i, task in enumerate(tasks):
            if task["status"] == "running" and task.get("started_at"):
                try:
                    started_at = datetime.fromisoformat(task["started_at"].replace("Z", "+00:00"))
                    elapsed = (now - started_at).total_seconds()
                    if elapsed > task_timeout:
                        stalled_tasks.append((i, task, elapsed))
                except (ValueError, TypeError):
                    # Invalid timestamp, treat as stalled
                    stalled_tasks.append((i, task, 0))

        # Report stalled tasks
        if stalled_tasks:
            print("\n  WARNING: Found stalled tasks:")
            for idx, task, elapsed in stalled_tasks:
                print(f"    Task {idx + 1}: {task['title']} (stalled for {elapsed:.0f}s)")
                # Mark as failed so they can be retried
                self.state.update_task(
                    idx,
                    {
                        "status": "failed",
                        "result_summary": f"Task stalled (exceeded {task_timeout}s timeout)",
                    },
                )

        # Find next pending task
        next_idx = None
        for i, t in enumerate(tasks):
            if t["status"] in ("pending", "running"):
                # Re-check after marking stalled tasks as failed
                fresh_state = self.state.read()
                fresh_task = fresh_state["tasks"][i]
                if fresh_task["status"] in ("pending", "running"):
                    next_idx = i
                    break

        if next_idx is None:
            print("All tasks already completed.")
            self._cleanup()
            return

        # Re-install hook
        self.project_dir = Path(state_data["project_dir"])
        self.context_md = ContextMDManager(self.project_dir)
        install_hook(self.project_dir)

        # Reset status and persist current_task_index
        state_data["status"] = "running"
        state_data["current_task_index"] = next_idx
        self.state.write(state_data)

        # Mark task as running with timestamp
        self.state.mark_task_running(next_idx)

        task = tasks[next_idx]
        print(f"\n  > Resuming task {next_idx + 1}/{len(tasks)}: {task['title']}")
        launch_agent_task(
            str(self.project_dir),
            task["file"],
            state_data.get("config", {}),
        )

        self._poll_until_complete()
        self._cleanup()

    def _poll_until_complete(self, poll_interval: float = 3.0):
        """Poll state.json until all tasks are done or aborted."""
        last_index = -1

        while True:
            if self.shutting_down:
                # Signal handler set the flag — do the I/O cleanup here (safe)
                try:
                    if self.state.exists():
                        self.state.set_status("aborted", "User interrupted")
                except Exception:
                    pass
                break

            time.sleep(poll_interval)

            try:
                state_data = self.state.read()
            except (json.JSONDecodeError, OSError):
                continue

            status = state_data.get("status", "")
            if status in ("completed", "aborted"):
                break

            current_idx = state_data.get("current_task_index", 0)
            tasks = state_data.get("tasks", [])
            total = len(tasks)

            # Print progress
            if current_idx != last_index:
                completed = sum(1 for t in tasks if t["status"] in ("completed", "failed"))
                running = sum(1 for t in tasks if t["status"] == "running")
                cost = state_data.get("total_cost_usd", 0)

                if running > 0:
                    running_task = next((t for t in tasks if t["status"] == "running"), None)
                    name = running_task["title"] if running_task else "?"
                    print(f"  [{completed}/{total}] Running: {name} (${cost:.2f} spent)")

                last_index = current_idx

            # Check if all done
            all_done = all(t["status"] in ("completed", "failed") for t in tasks)
            if all_done:
                break

            # Stall detection
            for t in tasks:
                if t["status"] == "running" and t.get("started_at"):
                    try:
                        started = datetime.fromisoformat(t["started_at"])
                        elapsed = (datetime.now(timezone.utc) - started).total_seconds()
                        if elapsed > self.args.task_timeout:
                            print(f"  WARNING: Task {t['index'] + 1} stalled ({elapsed:.0f}s)")
                            self.state.update_task(
                                t["index"],
                                {"status": "failed", "result_summary": "Timeout / stall detected"},
                            )
                    except (ValueError, TypeError):
                        pass

    def _poll_until_batch_complete(self, batch_num: int, poll_interval: float = 3.0):
        """Poll until a specific batch is done."""
        last_index = -1

        while True:
            if self.shutting_down:
                try:
                    if self.state.exists():
                        self.state.set_status("aborted", "User interrupted")
                except Exception:
                    pass
                break

            time.sleep(poll_interval)

            try:
                state_data = self.state.read()
            except (json.JSONDecodeError, OSError):
                continue

            status = state_data.get("status", "")
            if status in ("aborted",):
                break

            batch = state_data.get("batches", {}).get(str(batch_num), {})
            if batch.get("status") == "completed":
                break

            # Print progress
            current_idx = state_data.get("current_task_index", 0)
            if current_idx != last_index:
                batch_indices = batch.get("task_indices", [])
                tasks = state_data.get("tasks", [])
                completed = sum(
                    1
                    for i in batch_indices
                    if i < len(tasks) and tasks[i]["status"] in ("completed", "failed")
                )
                total = len(batch_indices)
                cost = state_data.get("total_cost_usd", 0)

                running_task = next(
                    (
                        tasks[i]
                        for i in batch_indices
                        if i < len(tasks) and tasks[i]["status"] == "running"
                    ),
                    None,
                )
                if running_task:
                    print(
                        f"  [{completed}/{total}] Running: {running_task['title']} (${cost:.2f} spent)"
                    )

                last_index = current_idx

            # Check if all batch tasks done
            batch_indices = batch.get("task_indices", [])
            tasks = state_data.get("tasks", [])
            all_done = all(
                tasks[i]["status"] in ("completed", "failed")
                for i in batch_indices
                if i < len(tasks)
            )
            if all_done:
                break

    def _cleanup(self):
        """Clean up after orchestration."""
        self.logger.section("Results")

        if self.state.exists():
            state_data = self.state.read()
            tasks = state_data.get("tasks", [])
            completed = sum(1 for t in tasks if t["status"] == "completed")
            failed = sum(1 for t in tasks if t["status"] == "failed")
            cost = state_data.get("total_cost_usd", 0)

            self.logger.info(f"Completed: {completed}/{len(tasks)} tasks")
            if failed:
                self.logger.warning(f"Failed: {failed} tasks")
            self.logger.info(f"Cost: ${cost:.2f}")
            print()

            # Display task summary using rich table if available
            self.logger.task_summary(tasks, cost)

            if state_data.get("status") != "aborted":
                state_data["status"] = "completed"
                self.state.write(state_data)

        # Restore project
        try:
            self.context_md.restore()
        except Exception:
            pass

        try:
            uninstall_hook(self.project_dir)
        except Exception:
            pass

        self.logger.success(f"Done. State saved to: {self.state_path}")

        # Close logger
        self.logger.close()


