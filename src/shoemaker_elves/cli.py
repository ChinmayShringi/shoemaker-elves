def get_orchestrator_dir():
    """Get the orchestrator installation directory (where this package is installed)."""
    return Path(__file__).parent.resolve()


def install_hook(project_dir: Path):
    """Install the SessionEnd hook into the project's settings.local.json."""
    config_dir = project_dir / ".claude"
    config_dir.mkdir(exist_ok=True)

    settings_path = config_dir / "settings.local.json"
    hook_handler = str(get_orchestrator_dir() / "hook_handler.py")

    # Read existing settings if present
    existing = {}
    if settings_path.exists():
        try:
            existing = json.loads(settings_path.read_text())
        except json.JSONDecodeError:
            existing = {}

    # Merge permissions
    permissions = existing.get("permissions", {})
    allow = set(permissions.get("allow", []))
    allow.update(["Bash", "Read", "Write", "Edit", "Glob", "Grep"])
    permissions["allow"] = sorted(allow)

    # Merge hook (preserve existing hooks for other events)
    existing["permissions"] = permissions
    hooks = existing.get("hooks", {})
    hooks["SessionEnd"] = [
        {
            "hooks": [
                {
                    "type": "command",
                    "command": hook_handler,
                    "timeout": 30,
                }
            ]
        }
    ]
    existing["hooks"] = hooks

    settings_path.write_text(json.dumps(existing, indent=2))
    print(f"  Installed SessionEnd hook → {hook_handler}")

    # Write reference file so hook_handler can find state.json
    ref_path = config_dir / "orchestrator_ref.json"
    ref_path.write_text(
        json.dumps(
            {
                "state_file": str(get_orchestrator_dir() / "state.json"),
                "orchestrator_dir": str(get_orchestrator_dir()),
            },
            indent=2,
        )
    )


def uninstall_hook(project_dir: Path):
    """Remove the orchestrator hook from settings.local.json."""
    settings_path = project_dir / ".claude" / "settings.local.json"
    ref_path = project_dir / ".claude" / "orchestrator_ref.json"

    if settings_path.exists():
        try:
            settings = json.loads(settings_path.read_text())
            settings.pop("hooks", None)
            settings_path.write_text(json.dumps(settings, indent=2))
            print("  Removed hook from settings.local.json")
        except json.JSONDecodeError:
            pass

    if ref_path.exists():
        ref_path.unlink()


