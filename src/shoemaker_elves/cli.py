def discover_manual_tasks() -> list[dict]:
    """Discover task files in the tasks/ directory, sorted numerically."""
    orchestrator_dir = get_orchestrator_dir()
    tasks_dir = orchestrator_dir / "tasks"
    if not tasks_dir.exists():
        return []

    task_files = []
    for f in tasks_dir.iterdir():
        if f.suffix == ".md" and f.stem.isdigit():
            task_files.append((int(f.stem), f))

    # Sort by number
    task_files.sort(key=lambda x: x[0])

    tasks = []
    for num, filepath in task_files:
        content = filepath.read_text().strip()
        # Extract title from first heading or filename
        title = f"Task {num}"
        for line in content.split("\n"):
            line = line.strip()
            if line.startswith("# "):
                title = line[2:].strip()
                break

        tasks.append(
            {
                "title": title,
                "file": f"tasks/{filepath.name}",
            }
        )

    return tasks


