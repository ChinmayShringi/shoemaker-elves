def launch_agent_task(project_dir: str, task_file: str, config: dict):
    """Launch an AI agent process for a task."""
    orchestrator_dir = get_orchestrator_dir()
    task_path = orchestrator_dir / task_file
    if not task_path.exists():
        print(f"  ERROR: Task file not found: {task_path}")
        return None

    prompt = task_path.read_text().strip()
    if not prompt:
        print(f"  ERROR: Task file is empty: {task_path}")
        return None

    cmd = [
        "claude",
        "-p",
        prompt,
        "--output-format",
        "json",
    ]

    agent_model = config.get("agent_model")
    if agent_model:
        cmd.extend(["--model", agent_model])

    proc = subprocess.Popen(
        cmd,
        cwd=project_dir,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        start_new_session=True,
    )

    return proc


