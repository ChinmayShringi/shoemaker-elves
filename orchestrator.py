def parse_args():
    parser = argparse.ArgumentParser(
        description="GPT Agent Orchestrator: Run tasks through an AI coding agent with hook-driven chaining.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Manual mode — run pre-created task files
  python orchestrator.py ~/projects/my-app

  # GPT mode — GPT generates and manages tasks
  python orchestrator.py ~/projects/my-app --gpt -d "Build a todo app with auth"

  # Resume after interruption
  python orchestrator.py ~/projects/my-app --resume
        """,
    )

    parser.add_argument("project_dir", help="Path to the target project directory")

    # GPT mode
    parser.add_argument("--gpt", action="store_true", help="Enable GPT orchestration mode")
    parser.add_argument("-d", "--description", help="Project description (required with --gpt)")
    parser.add_argument("--gpt-model", default="gpt-5.2", help="GPT model (default: gpt-5.2)")
    parser.add_argument("--max-batches", type=int, default=5, help="Max GPT planning rounds (default: 5)")
    parser.add_argument("--batch-size", type=int, default=5, help="Tasks per batch (default: 5)")

    # Agent options
    parser.add_argument("--agent-model", default="sonnet", help="AI agent model (default: sonnet)")
    parser.add_argument("--max-cost-usd", type=float, default=50.0, help="Cost ceiling in USD (default: 50.0)")
    parser.add_argument("--task-timeout", type=int, default=600, help="Max seconds per task (default: 600)")

    # Other
    parser.add_argument("--resume", action="store_true", help="Resume from existing state")
    parser.add_argument("--verbose", action="store_true", help="Detailed logging")
    parser.add_argument("--openai-api-key", help="OpenAI API key (or use OPENAI_API_KEY env)")

    return parser.parse_args()


