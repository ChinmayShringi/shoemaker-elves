#!/usr/bin/env python3
"""
GPT Agent Orchestrator
======================

A standalone CLI tool that runs a queue of tasks through an AI coding
agent using a hook-driven chain. Tasks can be manual markdown files or
auto-generated by GPT.

Usage:
  Manual mode:  python orchestrator.py ~/projects/my-app
  GPT mode:     python orchestrator.py ~/projects/my-app --gpt -d "Build a REST API"

Tasks are placed in the tasks/ directory as numbered markdown files:
  tasks/1.md, tasks/2.md, tasks/3.md, ...
"""

