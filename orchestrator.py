class ContextMDManager:
    """Manages the context file (CLAUDE.md) in the target project directory."""

    def __init__(self, project_dir: Path):
        self.context_md = project_dir / "CLAUDE.md"
        self.backup_path = project_dir / ".claude" / "CLAUDE.md.orchestrator_backup"
        self.original_existed = self.context_md.exists()

    def backup(self):
        """Back up existing context file before orchestration."""
        if self.original_existed:
            self.backup_path.parent.mkdir(parents=True, exist_ok=True)
            self.backup_path.write_text(self.context_md.read_text())
            print(f"  Backed up existing context file")

    def restore(self):
        """Restore original context file after orchestration."""
        if self.backup_path.exists():
            self.context_md.write_text(self.backup_path.read_text())
            self.backup_path.unlink()
            print(f"  Restored original CLAUDE.md")
        elif not self.original_existed and self.context_md.exists():
            self.context_md.unlink()
            print(f"  Removed orchestrator CLAUDE.md")

    def write_initial(self, description: str = "", cumulative_summary: str = ""):
        """Write initial CLAUDE.md for the first task."""
        lines = [
            "# Orchestrator Context",
            "",
            "You are executing a task as part of an automated pipeline.",
            "Complete the task in your prompt thoroughly and precisely.",
            "Do not ask clarifying questions — make reasonable assumptions.",
            "Focus on writing working code.",
            "",
        ]

        if description:
            lines.extend([
                "## Project Description",
                description,
                "",
            ])

        lines.extend([
            "## Progress So Far",
            "(No tasks completed yet)",
            "",
        ])

        if cumulative_summary:
            lines.extend([
                "## Cumulative Summary",
                cumulative_summary,
                "",
            ])

        # Preserve original content
        if self.backup_path.exists():
            lines.extend([
                "---",
                "## Original Project Instructions",
                self.backup_path.read_text(),
            ])

        self.context_md.write_text("\n".join(lines))

    def rewrite_with_summary(self, description: str, cumulative_summary: str):
        """Rewrite CLAUDE.md with updated cumulative summary (between batches)."""
        self.write_initial(description=description, cumulative_summary=cumulative_summary)


