class Orchestrator:
    def __init__(self, args):
        self.args = args
        self.project_dir = Path(args.project_dir).resolve()
        self.state_path = str(ORCHESTRATOR_DIR / "state.json")
        self.state = State(self.state_path)
        self.context_md = ContextMDManager(self.project_dir)
        self.gpt = None
        self.shutting_down = False

        # Set up signal handler for graceful shutdown
        signal.signal(signal.SIGINT, self._handle_shutdown)
        signal.signal(signal.SIGTERM, self._handle_shutdown)

    def _handle_shutdown(self, signum, frame):
        """Graceful shutdown: set flag, let the polling loop handle cleanup.

        Avoids file I/O in signal handler to prevent deadlocks if signal
        arrives while a file lock is held.
        """
        if self.shutting_down:
            # Second interrupt — force exit
            print("\nForce quitting...")
            sys.exit(1)

        self.shutting_down = True
        print("\n\nShutting down gracefully...")
        print("  (Current task will finish but no new tasks will start)")

    def validate(self):
        """Validate prerequisites."""
        if not self.project_dir.is_dir():
            print(f"Error: Project directory not found: {self.project_dir}")
            sys.exit(1)

        # Check agent CLI
        try:
            result = subprocess.run(
                ["claude", "--version"],
                capture_output=True,
                text=True,
                timeout=10,
            )
            if result.returncode != 0:
                print("Error: AI agent CLI not found or not working")
                sys.exit(1)
        except (FileNotFoundError, subprocess.TimeoutExpired):
            print("Error: AI agent CLI not found. Install it first.")
            sys.exit(1)

        if self.args.gpt:
            if not self.args.description:
                print("Error: --description is required with --gpt mode")
                sys.exit(1)

            api_key = self.args.openai_api_key or os.environ.get("OPENAI_API_KEY")
            if not api_key:
                print("Error: OpenAI API key not found. Set OPENAI_API_KEY or use --openai-api-key")
                sys.exit(1)

            lazy_import_gpt()
            self.gpt = GPTPlanner(api_key=api_key, model=self.args.gpt_model)

    def run(self):
        """Main orchestration loop."""
        self.validate()
        print(f"\n{'='*60}")
        print(f"  GPT Agent Orchestrator")
        print(f"{'='*60}")
        print(f"  Project:  {self.project_dir}")
        print(f"  Mode:     {'GPT' if self.args.gpt else 'Manual'}")
        print(f"  Agent:    {self.args.agent_model}")
        if self.args.gpt:
            print(f"  GPT:      {self.args.gpt_model}")
            print(f"  Batches:  {self.args.max_batches} x {self.args.batch_size} tasks")
        print(f"  Cost cap: ${self.args.max_cost_usd:.2f}")
        print(f"{'='*60}\n")

        if self.args.resume:
            self._resume()
        elif self.args.gpt:
            self._run_gpt_mode()
        else:
            self._run_manual_mode()

    def _run_manual_mode(self):
        """Run tasks from tasks/ directory."""
        tasks = discover_manual_tasks()
        if not tasks:
            print("No task files found in tasks/ directory.")
            print("Create numbered markdown files: tasks/1.md, tasks/2.md, ...")
            sys.exit(1)

        print(f"Found {len(tasks)} task(s):")
        for t in tasks:
            print(f"  • {t['file']}: {t['title']}")
        print()

        config = {
            "agent_model": self.args.agent_model,
            "max_cost_usd": self.args.max_cost_usd,
            "task_timeout": self.args.task_timeout,
        }

        # Initialize state
        State.create_initial(
            path=self.state_path,
            project_dir=str(self.project_dir),
            orchestrator_dir=str(ORCHESTRATOR_DIR),
            tasks=tasks,
            config=config,
            mode="manual",
        )

        # Set up project
        self.context_md.backup()
        self.context_md.write_initial()
        install_hook(self.project_dir)

        # Mark first task as running
        self.state.update_task(0, {"status": "running"})

        # Launch first task
        first_task = tasks[0]
        print(f"> Starting task 1/{len(tasks)}: {first_task['title']}")
        launch_agent_task(str(self.project_dir), first_task["file"], config)

        # Poll until done
        self._poll_until_complete()

        # Cleanup
        self._cleanup()

    def _run_gpt_mode(self):
        """Run with GPT generating batches of tasks."""
        description = self.args.description

        # Read description from file if it's a path
        if os.path.isfile(description):
            description = Path(description).read_text().strip()

        config = {
            "agent_model": self.args.agent_model,
            "max_cost_usd": self.args.max_cost_usd,
            "task_timeout": self.args.task_timeout,
            "gpt_model": self.args.gpt_model,
        }

        self.context_md.backup()
        install_hook(self.project_dir)

        cumulative_summary = ""
        previous_results = []
        total_task_index = 0

        for batch_num in range(1, self.args.max_batches + 1):
            if self.shutting_down:
                break

            print(f"\n{'─'*50}")
            print(f"  Batch {batch_num}/{self.args.max_batches}")
            print(f"{'─'*50}")

            # Ask GPT to plan tasks
            print(f"  Asking GPT to plan batch {batch_num}...")
            gpt_tasks = self.gpt.plan_batch(
                description=description,
                batch_num=batch_num,
                max_batches=self.args.max_batches,
                batch_size=self.args.batch_size,
                previous_results=previous_results,
                cumulative_summary=cumulative_summary,
            )

            if not gpt_tasks:
                print("  GPT says project is complete!")
                break

            # Write tasks to files
            task_entries = self.gpt.write_tasks_to_files(
                gpt_tasks, str(ORCHESTRATOR_DIR), start_index=total_task_index
            )

            print(f"  Generated {len(task_entries)} tasks:")
            for t in task_entries:
                print(f"    • {t['title']}")

            # Create or update state
            if batch_num == 1:
                State.create_initial(
                    path=self.state_path,
                    project_dir=str(self.project_dir),
                    orchestrator_dir=str(ORCHESTRATOR_DIR),
                    tasks=task_entries,
                    config=config,
                    mode="gpt",
                )
            else:
                # Add new batch tasks to existing state
                state_data = self.state.read()
                new_indices = []
                for t in task_entries:
                    idx = len(state_data["tasks"])
                    new_indices.append(idx)
                    state_data["tasks"].append({
                        "index": idx,
                        "title": t["title"],
                        "file": t["file"],
                        "status": "pending",
                        "session_id": None,
                        "transcript_path": None,
                        "result_summary": None,
                        "files_modified": [],
                        "cost_usd": 0,
                    })
                state_data["current_batch"] = batch_num
                state_data["current_task_index"] = new_indices[0]
                state_data["batches"][str(batch_num)] = {
                    "task_indices": new_indices,
                    "status": "running",
                }
                self.state.write(state_data)

            # Update CLAUDE.md
            self.context_md.rewrite_with_summary(description, cumulative_summary)

            # Mark first task of batch as running
            state_data = self.state.read()
            first_idx = state_data["current_task_index"]
            self.state.update_task(first_idx, {"status": "running"})

            # Launch first task
            first_task = task_entries[0]
            print(f"\n  > Starting: {first_task['title']}")
            launch_agent_task(str(self.project_dir), first_task["file"], config)

            # Poll until batch complete
            self._poll_until_batch_complete(batch_num)

            if self.shutting_down:
                break

            # Gather batch results for GPT assessment
            state_data = self.state.read()
            batch_info = state_data["batches"][str(batch_num)]
            batch_results = []
            for idx in batch_info["task_indices"]:
                task = state_data["tasks"][idx]
                batch_results.append({
                    "title": task["title"],
                    "success": task["status"] == "completed",
                    "result_summary": task.get("result_summary", ""),
                    "files_modified": task.get("files_modified", []),
                    "errors": [],
                })

            # GPT assessment
            print(f"\n  Asking GPT to assess batch {batch_num}...")
            assessment = self.gpt.assess_batch(
                description=description,
                batch_num=batch_num,
                batch_results=batch_results,
                previous_summary=cumulative_summary,
            )

            cumulative_summary = assessment.get("cumulative_summary", cumulative_summary)
            previous_results = batch_results
            total_task_index += len(task_entries)

            complete_pct = assessment.get("completion_percentage", 0)
            print(f"  Assessment: {complete_pct}% complete")
            if assessment.get("issues"):
                for issue in assessment["issues"]:
                    print(f"    WARNING: {issue}")

            if assessment.get("project_complete"):
                print(f"\n  GPT says project is complete!")
                break

            # Check cost
            if state_data.get("total_cost_usd", 0) >= self.args.max_cost_usd:
                print(f"\n  Cost ceiling reached: ${state_data['total_cost_usd']:.2f}")
                break

        self._cleanup()

    def _resume(self):
        """Resume from existing state file."""
        if not self.state.exists():
            print("No state file found. Nothing to resume.")
            sys.exit(1)

        state_data = self.state.read()
        print(f"Resuming from state: {state_data.get('status')}")
        print(f"  Tasks: {len(state_data.get('tasks', []))}")
        print(f"  Cost so far: ${state_data.get('total_cost_usd', 0):.2f}")

        # Find next pending task
        tasks = state_data.get("tasks", [])
        next_idx = None
        for i, t in enumerate(tasks):
            if t["status"] in ("pending", "running"):
                next_idx = i
                break

        if next_idx is None:
            print("All tasks already completed.")
            self._cleanup()
            return

        # Re-install hook
        self.project_dir = Path(state_data["project_dir"])
        self.context_md = ContextMDManager(self.project_dir)
        install_hook(self.project_dir)

        # Reset status and persist current_task_index
        state_data["status"] = "running"
        state_data["current_task_index"] = next_idx
        self.state.write(state_data)
        self.state.update_task(next_idx, {"status": "running"})

        task = tasks[next_idx]
        print(f"\n  > Resuming task {next_idx + 1}/{len(tasks)}: {task['title']}")
        launch_agent_task(
            str(self.project_dir),
            task["file"],
            state_data.get("config", {}),
        )

        self._poll_until_complete()
        self._cleanup()

    def _poll_until_complete(self, poll_interval: float = 3.0):
        """Poll state.json until all tasks are done or aborted."""
        last_index = -1

        while True:
            if self.shutting_down:
                # Signal handler set the flag — do the I/O cleanup here (safe)
                try:
                    if self.state.exists():
                        self.state.set_status("aborted", "User interrupted")
                except Exception:
                    pass
                break

            time.sleep(poll_interval)

            try:
                state_data = self.state.read()
            except (json.JSONDecodeError, OSError):
                continue

            status = state_data.get("status", "")
            if status in ("completed", "aborted"):
                break

            current_idx = state_data.get("current_task_index", 0)
            tasks = state_data.get("tasks", [])
            total = len(tasks)

            # Print progress
            if current_idx != last_index:
                completed = sum(1 for t in tasks if t["status"] in ("completed", "failed"))
                running = sum(1 for t in tasks if t["status"] == "running")
                cost = state_data.get("total_cost_usd", 0)

                if running > 0:
                    running_task = next(
                        (t for t in tasks if t["status"] == "running"), None
                    )
                    name = running_task["title"] if running_task else "?"
                    print(f"  [{completed}/{total}] Running: {name} (${cost:.2f} spent)")

                last_index = current_idx

            # Check if all done
            all_done = all(t["status"] in ("completed", "failed") for t in tasks)
            if all_done:
                break

            # Stall detection
            for t in tasks:
                if t["status"] == "running" and t.get("started_at"):
                    try:
                        started = datetime.fromisoformat(t["started_at"])
                        elapsed = (
                            datetime.now(timezone.utc) - started
                        ).total_seconds()
                        if elapsed > self.args.task_timeout:
                            print(f"  WARNING: Task {t['index']+1} stalled ({elapsed:.0f}s)")
                            self.state.update_task(
                                t["index"],
                                {"status": "failed", "result_summary": "Timeout / stall detected"},
                            )
                    except (ValueError, TypeError):
                        pass

    def _poll_until_batch_complete(self, batch_num: int, poll_interval: float = 3.0):
        """Poll until a specific batch is done."""
        last_index = -1

        while True:
            if self.shutting_down:
                try:
                    if self.state.exists():
                        self.state.set_status("aborted", "User interrupted")
                except Exception:
                    pass
                break

            time.sleep(poll_interval)

            try:
                state_data = self.state.read()
            except (json.JSONDecodeError, OSError):
                continue

            status = state_data.get("status", "")
            if status in ("aborted",):
                break

            batch = state_data.get("batches", {}).get(str(batch_num), {})
            if batch.get("status") == "completed":
                break

            # Print progress
            current_idx = state_data.get("current_task_index", 0)
            if current_idx != last_index:
                batch_indices = batch.get("task_indices", [])
                tasks = state_data.get("tasks", [])
                completed = sum(
                    1
                    for i in batch_indices
                    if i < len(tasks) and tasks[i]["status"] in ("completed", "failed")
                )
                total = len(batch_indices)
                cost = state_data.get("total_cost_usd", 0)

                running_task = next(
                    (tasks[i] for i in batch_indices if i < len(tasks) and tasks[i]["status"] == "running"),
                    None,
                )
                if running_task:
                    print(f"  [{completed}/{total}] Running: {running_task['title']} (${cost:.2f} spent)")

                last_index = current_idx

            # Check if all batch tasks done
            batch_indices = batch.get("task_indices", [])
            tasks = state_data.get("tasks", [])
            all_done = all(
                tasks[i]["status"] in ("completed", "failed")
                for i in batch_indices
                if i < len(tasks)
            )
            if all_done:
                break

    def _cleanup(self):
        """Clean up after orchestration."""
        print(f"\n{'='*60}")

        if self.state.exists():
            state_data = self.state.read()
            tasks = state_data.get("tasks", [])
            completed = sum(1 for t in tasks if t["status"] == "completed")
            failed = sum(1 for t in tasks if t["status"] == "failed")
            cost = state_data.get("total_cost_usd", 0)

            print(f"  Results:")
            print(f"    Completed: {completed}/{len(tasks)} tasks")
            if failed:
                print(f"    Failed:    {failed} tasks")
            print(f"    Cost:      ${cost:.2f}")
            print()

            # Print per-task summary
            for t in tasks:
                icon = "[+]" if t["status"] == "completed" else "[x]" if t["status"] == "failed" else "[ ]"
                print(f"    {icon} {t['title']}")
                if t.get("files_modified"):
                    print(f"      Files: {', '.join(t['files_modified'][:5])}")

            if state_data.get("status") != "aborted":
                state_data["status"] = "completed"
                self.state.write(state_data)

        # Restore project
        try:
            self.context_md.restore()
        except Exception:
            pass

        try:
            uninstall_hook(self.project_dir)
        except Exception:
            pass

        print(f"\n{'='*60}")
        print(f"  Done. State saved to: {self.state_path}")
        print(f"{'='*60}\n")


